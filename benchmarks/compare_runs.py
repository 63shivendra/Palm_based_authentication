#!/usr/bin/env python3
"""
benchmarks/compare_runs.py - compare the v4 pipeline with the original benchmark results.

  python benchmarks/compare_runs.py [--new <run>] [--old <run>]
Writes benchmarks/results/COMPARISON.md and benchmarks/results/plots/comparison.png.

Sources
  new      the latest run with v4 (default benchmarks/results/runs/20261115-0239-quick): v4 and v3c on the SAME test
           identities, the only like-for-like comparison
  old      the original quick benchmark (default runs/20261114-1759-quick): v3c, v3cr, v2, v1 on its own identity split
  large    the original large benchmark of 13 Nov (benchmarks/results/benchmark_results.csv, robustness.csv, latency.csv)
"""
import argparse
import csv
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import bench_report as BR  # noqa: E402

RES = os.path.join(HERE, "results")
NAMES = {"tongji": "Tongji", "bjtu2": "BJTU", "gabor": "Gabor", "11khands": "11k Hands", "xinhua": "XINHUA",
         "palmmatchdb": "PalmMatchDB", "real": "Own photos"}
ORDER = ["tongji", "bjtu2", "gabor", "11khands", "xinhua", "palmmatchdb", "real"]


def metrics(run):
    rows = list(csv.DictReader(open(os.path.join(run, "metrics.csv"), encoding="utf-8")))
    out = {}
    for r in rows:
        if r["enrolled_photos"] == "1":
            f = lambda k: float(r[k]) if r[k] not in ("", None) else None
            out[r["dataset"], r["method"]] = dict(EER=f("EER"), FAR=f("FAR"), FRR=f("FRR"), FTE=f("FTE"),
                                                  ids=int(r["test_identities"]), gen=int(r["genuine_comparisons"]),
                                                  imp=int(r["impostor_comparisons"]))
    return out


def pct(v, nd=2):
    return "–" if v is None else f"{v * 100:.{nd}f}%"


def delta(a, b):
    """Change from a (before) to b (after), in percentage points, with a word."""
    if a is None or b is None:
        return "–"
    d = (b - a) * 100
    if abs(d) < 0.005:
        return "same"
    return f"{'better' if d < 0 else 'worse'} by {abs(d):.2f} pts"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--new", default=os.path.join(RES, "runs", "20261115-0239-quick"))
    ap.add_argument("--old", default=os.path.join(RES, "runs", "20261114-1759-quick"))
    a = ap.parse_args()
    new, old = metrics(a.new), metrics(a.old)
    large = list(csv.DictReader(open(os.path.join(RES, "benchmark_results.csv"), encoding="utf-8")))
    md = ["# v4 compared with the original benchmark", "",
          f"Generated by `benchmarks/compare_runs.py` from `{os.path.relpath(a.new, RES)}` (v4 run), "
          f"`{os.path.relpath(a.old, RES)}` (original quick benchmark, 14 Nov) and `benchmark_results.csv` (original large "
          "benchmark, 13 Nov). EER does not depend on the threshold; FRR includes photos a quality gate sent back "
          "(failure to enrol). Lower is better everywhere.", ""]

    # 1. like for like
    md += ["## 1. Like for like: v3c and v4 on the same test identities", "",
           "Same run, same photos, same comparisons. This is the fair measure of what the changes did.", "",
           "| Dataset | Test identities | v3c EER | v4 EER | EER change | v3c FRR | v4 FRR | FRR change | v4 retake requests | FAR (both) |",
           "|---|---|---|---|---|---|---|---|---|---|"]
    for d in ORDER:
        c, v = new.get((d, "v3c")), new.get((d, "v4"))
        if not (c and v):
            continue
        md.append(f"| {NAMES[d]} | {v['ids']} | {pct(c['EER'])} | **{pct(v['EER'])}** | {delta(c['EER'], v['EER'])} | "
                  f"{pct(c['FRR'], 1)} | **{pct(v['FRR'], 1)}** | {delta(c['FRR'], v['FRR'])} | {pct(v['FTE'], 1)} | "
                  f"{pct(c['FAR'])} / {pct(v['FAR'])} |")
    md += ["", "Up to 500 impostor comparisons per dataset, so 0.00% means below about 0.6% (rule of 3).", ""]

    # 2. original quick benchmark
    md += ["## 2. Against the original quick benchmark (14 Nov)", "",
           "The original run drew its own test identities, so these are **different people** from the v4 run (same "
           "datasets, same sample sizes). Read it as context, not as a like-for-like result.", "",
           "| Dataset | v3c EER (original) | v3cr EER (original) | v2 EER (original) | **v4 EER (new)** | v3c FRR (original) | **v4 FRR (new)** |",
           "|---|---|---|---|---|---|---|"]
    for d in ORDER:
        o3, ocr, o2, v = old.get((d, "v3c")), old.get((d, "v3cr")), old.get((d, "v2")), new.get((d, "v4"))
        if not v:
            continue
        g = lambda x, k, nd=2: pct(x[k], nd) if x else "–"
        md.append(f"| {NAMES[d]} | {g(o3, 'EER')} | {g(ocr, 'EER')} | {g(o2, 'EER')} | **{g(v, 'EER')}** | "
                  f"{g(o3, 'FRR', 1)} | **{g(v, 'FRR', 1)}** |")
    md.append("")

    # 3. original large benchmark
    md += ["## 3. Against the original large benchmark (13 Nov)", "",
           "The large run used many more comparisons (Tongji: 600 palms, 5,400 genuine / 30,000 impostor). **v4 has not been "
           "run at this scale yet**: `.\\bench.ps1 run --profile full` on the GPU desktop produces the like-for-like numbers.", "",
           "| Dataset | Method | Identities | Genuine / impostor | EER | FRR |", "|---|---|---|---|---|---|"]
    for r in large:
        if r["enrolled_photos"] != "1":
            continue
        md.append(f"| {r['dataset']} | {r['method']} | {r['identities']} | {int(r['genuine_comparisons']):,} / "
                  f"{int(r['impostor_comparisons']):,} | {float(r['EER_pct']):.2f}% | {float(r['FRR_pct']):.2f}% |")
    md.append("")

    # 4. robustness
    rob_new = json.load(open(os.path.join(a.new, "robustness.json")))
    rob_old = json.load(open(os.path.join(a.old, "robustness.json")))
    conds = list(dict.fromkeys(x["condition"] for x in rob_new))
    get = lambda rows, m, c: next((x for x in rows if x["method"] == m and x["condition"] == c), None)
    md += ["## 4. Robustness (Tongji, clean enrolled photo vs degraded probe)", "",
           "FRR, threshold as shipped. Original: 14 Nov quick run (20 palms). New: 20 Tongji TEST palms. For v4 the share "
           "sent back for a retake is in brackets; none of the photos v4 accepted was falsely rejected under any condition "
           "except rotation.", "",
           "| Condition | v3c (original) | v3cr (original) | v3c (new) | **v4 (new)** |", "|---|---|---|---|---|"]
    for c in conds:
        o3, ocr, n3, v = get(rob_old, "v3c", c), get(rob_old, "v3cr", c), get(rob_new, "v3c", c), get(rob_new, "v4", c)
        f = lambda x: pct(x["FRR"], 0) if x else "–"
        vv = f"{pct(v['FRR'], 0)}" + (f" ({pct(v['gate_rejects'], 0)} retake)" if v and v.get("gate_rejects") else "") if v else "–"
        md.append(f"| {c} | {f(o3)} | {f(ocr)} | {f(n3)} | **{vv}** |")
    md.append("")

    # 5. latency
    lat = json.load(open(os.path.join(a.new, "results.json")))["latency"]["this_device"]
    st = lat["stages"]
    ms = lambda k: f"{st[k]['median']:,.0f} ms" if k in st else "–"
    md += ["## 5. Speed", "",
           "| Stage | Original, desktop GPU (13 Nov) | Original, desktop CPU (13 Nov) | New, this laptop CPU |", "|---|---|---|---|",
           f"| Hand detection | – | 35 ms | {ms('detect')} |",
           f"| Make template | 14 ms (DISK) | 184 ms (DISK) | v3c {ms('extract_v3c')}, v4 {ms('extract_v4')} |",
           f"| One comparison | v3c 21 ms | v3c 150 ms | v3c {ms('match_v3c')}, v4 {ms('match_v4')} |", "",
           "The laptop CPU is several times slower than the desktop. v4 adds about 15% to template creation (SIFT part) "
           "and about 45% to a comparison. The full run on the desktop measures v4 on the GPU; a faster variant (384 px, 512 "
           "keypoints) halves template time with the same DEV accuracy (`speed/`).", ""]

    # 6. capabilities
    md += ["## 6. What the system can do now that it could not before", "",
           "| Capability | Original | Now | Measured |", "|---|---|---|---|",
           "| Spoof detection | none | random finger-count liveness + screen/print check | replayed video passes 0-2.7% (simulated); "
           "genuine photos flagged 2.9%; simulated screen/print accepted 5.0% / 9.3%; real attacks not collected yet |",
           "| 1:N identification | none (1:1 only) | protected-vector shortlist + matcher | 240 palms: misses 2.67%, wrong person 0% |",
           "| Template protection | raw templates | cancellable IoM search template + encrypted keypoint templates | D_sys 0.035; "
           "a re-issued template does not match the old one |",
           "| Capture quality | blur and distance only | exposure, focus, faint creases, palm size, tilt, open hand, with a retake "
           "instruction | limits set on DEV photos |",
           "| Product | comparison dashboard | kiosk: register, automatic palm ID, duplicate check, pay, admin, audit log | end-to-end tests |",
           ""]
    md += ["## 7. Against published methods on the same datasets", "",
           "Charts made by `benchmarks/plot_literature.py`.", "",
           "**Like for like** (`plots/like_for_like.png`): two published methods re-implemented in `palm_match.py` and run "
           "on exactly the same test people and comparisons as v4: CompCode (Kong & Zhang 2004, our v1) and SIFT + RANSAC "
           "(Wu, Zhao & Bu 2014, our v2). v4 has the lowest or equal EER on every dataset except PalmMatchDB, where SIFT is "
           "lower (0.8% vs 1.3%). On BJTU: v4 10.2%, CompCode 11.6%, SIFT 12.7%, v3c 15.9%.", "",
           "![like for like](plots/like_for_like.png)", "",
           "**Published numbers** (`plots/literature_tongji.png`): only Tongji has published results we could find. "
           "No published palm results were found for PalmMatchDB, the Gabor set, 11k Hands (palm side) or BJTU v2; the "
           "paper introducing XINHUA (PeerJ CS 2025) could not be retrieved. On Tongji, our zero-shot v3c (0.054%, 600 palms) "
           "is about 40x below models trained on another dataset (2.2-2.9%), below hand-crafted CompCode (0.10%) and "
           "similar to several models trained on Tongji itself (DHPN 0.066%, PalmNet 0.03-0.17%); CCNet, CompNet and BOCV "
           "trained or tuned on Tongji are lower. Protocols differ between papers.", "",
           "![Tongji literature](plots/literature_tongji.png)", ""]
    md += ["## 8. Bottom line", "",
           "- On the same people, v4 lowers the error where v3c was weak (BJTU, Gabor) and removes the noise and JPEG "
           "failures, at the cost of more retake requests (PalmMatchDB: 21% of photos sent back).",
           "- Where v3c was already at 0%, v4 stays at 0%: the quick test cannot show smaller differences.",
           "- The quick runs are small. The full GPU run gives the numbers to quote and the GPU latency."]
    open(os.path.join(RES, "COMPARISON.md"), "w", encoding="utf-8").write("\n".join(md) + "\n")
    chart(new, old)
    print("\n".join(md))
    print("written", os.path.join(RES, "COMPARISON.md"))


def chart(new, old):
    plt = BR._plt()
    from matplotlib.patches import Patch
    series = [("v3c, original run (other people)", old, "v3c", "#f3c4a8"), ("v3c, same people as v4", new, "v3c", BR.COLOR["v3c"]),
              ("v4", new, "v4", BR.COLOR["v4"])]
    ds = [d for d in ORDER if (d, "v4") in new]
    fig, axs = plt.subplots(1, 2, figsize=(11, 0.9 + 0.62 * len(ds)), dpi=150)
    fig.subplots_adjust(left=0.11, right=0.97, top=1 - 1.25 / (0.9 + 0.62 * len(ds)), bottom=0.1, wspace=0.28)
    h = 0.8 / len(series)
    for ax, key, title in zip(axs, ("EER", "FRR"), ("Equal error rate", "Genuine users rejected (FRR, incl. retakes)")):
        vals = [m[d, s][key] for _, m, s, _ in series for d in ds if (d, s) in m and m[d, s][key] is not None]
        xmax = max(vals + [0.01]) * 1.3
        for j, (label, m, s, col) in enumerate(series):
            for i, d in enumerate(ds):
                if (d, s) not in m:
                    continue
                v = m[d, s][key]
                y = i + (j - 1) * h
                ax.barh(y, max(v, xmax * 0.004), height=h * 0.86, color=col, edgecolor=BR.SURFACE, linewidth=1)
                ax.text(max(v, xmax * 0.004) + xmax * 0.01, y, f"{v * 100:.1f}%", va="center", fontsize=7.5, color=BR.INK2)
        ax.set_yticks(range(len(ds)))
        ax.set_yticklabels([NAMES[d] for d in ds])
        ax.invert_yaxis()
        ax.set_xlim(0, xmax)
        ax.xaxis.set_major_formatter(lambda v, _: f"{v * 100:g}%")
        ax.set_title(title, fontsize=10, loc="left")
        ax.grid(axis="y", visible=False)
        ax.tick_params(length=0)
    fig.legend(handles=[Patch(color=c, label=l) for l, _, _, c in series], loc="upper left", ncol=3,
               bbox_to_anchor=(0.012, 1 - 0.7 / fig.get_size_inches()[1]), frameon=False, fontsize=8.5, labelcolor=BR.INK2,
               handlelength=1, columnspacing=1.6)
    BR._title(fig, "v4 compared with v3c", "Test identities, 1 enrolled photo, quick profile. Lower is better.")
    os.makedirs(os.path.join(RES, "plots"), exist_ok=True)
    fig.savefig(os.path.join(RES, "plots", "comparison.png"))
    plt.close(fig)


if __name__ == "__main__":
    main()
